// Verificación funcional de la muestra pública; nunca usa sesión de WordPress.
import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
const require=createRequire('/home/alberto/Trabajo/ETF/web/package.json');
const {chromium}=require('playwright-core');
const origin=process.argv[2]||'http://127.0.0.1:18086';
if(!['http://127.0.0.1:18086','https://facuso.cidonia.cloud'].includes(origin))throw Error('Destino no autorizado');
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:'block'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const assert=(ok,msg)=>{if(!ok)throw Error(msg);};
try{
 await page.goto(origin+'/territorios/granada/diputacion-de-granada/');
 const images=await page.locator('main img').evaluateAll(async es=>{await Promise.all(es.map(async e=>{e.loading='eager';await e.decode();}));return es.map(e=>({url:e.src,width:e.naturalWidth}));});
 assert(images.length===4&&images.every(e=>e.width>0),'Capturas ausentes');
 await page.locator('main audio').evaluate(el=>el.load());
 await page.waitForFunction(()=>document.querySelector('main audio').duration>0,{},{timeout:15000});
 const audioSeconds=await page.locator('main audio').evaluate(el=>el.duration);
 await page.locator('.fac-tcae-container summary').click();
 const root=page.locator('.fac-tcae');const cards=root.locator('fieldset');
 assert(await cards.count()===6,'Número de preguntas');
 const source=JSON.parse((await import('node:fs')).readFileSync('data/muestra-tcae.json','utf8'));
 for(let i=0;i<6;i++)await cards.nth(i).locator('input').nth(source.questions[i].correct).check();
 await root.locator('[data-tcae-check]').click();
 assert(await root.locator('[role=status]').textContent()==='Resultado: 6 / 6','Corrección de aciertos');
 assert(await root.locator('.fac-tcae-feedback:visible').count()===6,'Explicaciones');
 await root.locator('[data-tcae-reset]').click();
 assert(await root.locator('input:checked').count()===0,'Reinicio');
 await root.locator('[data-tcae-check]').click();
 assert(await root.locator('[role=status]').textContent()==='Resultado: 0 / 6','Preguntas sin responder');
 assert((await root.locator('.fac-tcae-feedback strong').allTextContents()).every(t=>t==='Sin responder'),'Etiquetas de no respondidas');
 await root.locator('[data-tcae-reset]').click();
 await cards.first().locator('input').nth((source.questions[0].correct+1)%4).check();
 await root.locator('[data-tcae-check]').click();
 assert(await root.locator('.is-wrong').count()===1,'Respuesta incorrecta');
 await root.locator('[data-tcae-reset]').click();
 await page.getByRole('heading',{name:'Cursos específicos para las OPE de la Diputación de Granada',exact:true}).scrollIntoViewIfNeeded();
 mkdirSync('imagenes/cursos-granada',{recursive:true});
 await page.screenshot({path:'imagenes/cursos-granada/facuso-resumen.png'});
 await cards.first().scrollIntoViewIfNeeded();
 await page.screenshot({path:'imagenes/cursos-granada/facuso-test.png'});
 await page.setViewportSize({width:390,height:844});
 const mobile=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}));
 assert(mobile.width===mobile.viewport,'Desbordamiento móvil');
 await cards.first().scrollIntoViewIfNeeded();
 await page.screenshot({path:'imagenes/cursos-granada/facuso-test-movil.png'});
 const external=await page.locator('main a[href^="https://uso.dipgra.cloud"]').evaluateAll(es=>es.every(e=>e.target==='_blank'&&e.rel.includes('noopener')));
 assert(external,'Enlaces externos');assert(errors.length===0,'Errores JavaScript');
 const report={origin,questions:6,correct:'6/6',empty:'0/6',wrong_answer:true,reset:true,feedback:6,images,audio_seconds:audioSeconds,mobile,external_new_tab:external,errors,private_data:false,source:source.source};
 writeFileSync('docs/evidencias/qa-cursos-granada.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
}finally{await browser.close();}
